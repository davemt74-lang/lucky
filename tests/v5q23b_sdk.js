/* V5Q.23B SDK consumer contract. */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const code=fs.readFileSync('sdk/lucky-game.js','utf8');
let listener=null;const sent=[];
const parent={postMessage(...args){sent.push(args)}};
const window={parent,addEventListener(name,callback){if(name==='message')listener=callback}};
vm.runInNewContext(code,{window});
const sdk=window.LuckyGameSDK;
assert.equal(sdk.version,'2.0.0');
assert.equal(Object.isFrozen(sdk),true);
assert.equal(sdk.sendInput('buzz','one'),false);
let states=[];const unsub=sdk.onState(s=>states.push(s.status));
listener({source:parent,data:{type:'lucky:state',state:{status:'active',version:1}}});
assert.equal(sdk.sendInput('buzz','one'),true);
assert.equal(sent.length,1);
assert.equal(sent[0][0].name,'buzz');
assert.equal(sent[0][0].value,'one');
assert.equal(sent[0][1],'*');
listener({source:{},data:{type:'lucky:state',state:{status:'ended'}}});
assert.equal(sdk.getState().status,'active');
listener({source:parent,data:{type:'lucky:state',state:{status:'paused'}}});
assert.equal(sdk.sendInput('buzz','two'),false);
assert.equal(sent.length,1);
assert.throws(()=>sdk.sendInput('../../admin',null),/Invalid/);
assert.throws(()=>sdk.sendInput('buzz',{unsafe:true}),/primitive/);
assert.throws(()=>sdk.sendInput('buzz','a'.repeat(241)),/primitive/);
assert.throws(()=>sdk.sendInput('buzz',1.25),/primitive/);
unsub();
assert.deepEqual(states,['active','paused']);
console.log('V5Q.23B SDK browser event contract passed');
